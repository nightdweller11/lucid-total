/** report.md: statistics of an import run and the evaluation (docs/10 §3 quotes these numbers). */

const STATES = ['todo', 'brief', 'doing', 'review', 'done', 'blocked'];
const count = (arr, key) => arr.reduce((m, x) => ((m[key(x)] = (m[key(x)] ?? 0) + 1), m), {});
const pct = (n, d) => (d ? `${Math.round((n / d) * 1000) / 10} %` : '—');
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const short = (s, n = 110) => {
  const t = esc(s);
  return t.length > n ? `${t.slice(0, n - 1)}…` : t;
};

function table(head, rows) {
  return [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
}

function list(items, fmt, cap) {
  const shown = items.slice(0, cap).map(fmt);
  const more = items.length > cap ? [`- … and ${items.length - cap} more (full list in \`evaluation.json\`)`] : [];
  return [...shown, ...more].join('\n') || '- none';
}

export function renderReport(r) {
  const items = r.checklistItems;
  const top = items.filter((i) => i.top_level);
  const fu = items.filter((i) => !i.top_level);
  const out = [];
  const p = (...l) => out.push(...l);
  const ev = r.evaluation;
  const done = ev.filter((e) => e.state === 'done');
  const s = r.meta.sanitizer;

  p('# Lucid Chat import report', '');
  p('Generated by `tools/import/lucid-chat/import.mjs` from the Lucid Chat repository. Deterministic for a given source; the source hashes below identify the input.', '');
  p('## 1. Sources and privacy filter', '');
  p(table(['Source', 'sha256 (16)'], Object.entries(r.meta.source_hashes).map(([k, v]) => [`\`${k}\``, `\`${v}\``])), '');
  p(`Files read in all: ${r.meta.source_files_read} (briefs, walkthrough and test reports included). Stripped from every output: **${s.email} email addresses, ${s.phone} phone numbers, ${s.secret} credential-looking tokens** (replaced by \`[email removed]\` / \`[phone removed]\` / \`[secret removed]\`).`, '');

  p('## 2. What was imported', '');
  const kinds = count(r.items, (i) => i.kind);
  p(table(['Output', 'Count'], [
    ['Checklist rows → items', items.length],
    ['… top-level rows (CT, P0–P4)', top.length],
    ['… follow-up rows', fu.length],
    ['Items by kind (all items)', Object.entries(kinds).map(([k, v]) => `${k} ${v}`).join(' · ')],
    ['Accounts and chores from `docs/07a`', r.accounts.length],
    ['Decisions (log entries, owner answers O<n>, open-decision cards, ADRs)', r.decisions.length],
    ["Owner's answers from the decisions page", r.answers.answers.length],
    ['Relations', r.relations.length],
    ['Evidence records', r.evidence.length],
    ['Briefs indexed', r.briefs.length],
    ['Walkthrough reports indexed', r.reports.filter((x) => x.type === 'walkthrough').length],
    ['Other test reports indexed (load, evals, gates, rc, reviews)', r.reports.filter((x) => x.type === 'report').length],
    ['Groupings', r.groupings.length],
  ]), '');
  const relRules = count(r.relations, (x) => `${x.type} · ${x.rule}`);
  p('Relations by type and rule:', '');
  p(table(['Type · rule', 'Count'], Object.entries(relRules).sort((a, b) => b[1] - a[1]).map(([k, v]) => [k, v])), '');
  const evTypes = count(r.evidence, (x) => x.type);
  p('Evidence records by type:', '');
  p(table(['Type', 'Count'], Object.entries(evTypes).sort((a, b) => b[1] - a[1]).map(([k, v]) => [k, v])), '');

  p('## 3. Rows per phase and workstream', '');
  const phases = ['CT', 'P0', 'P1', 'P2', 'P3', 'P4', null];
  p(table(['Phase', 'Top-level', 'Follow-up (phase inferred)', 'Done', 'Open'], phases.map((ph) => {
    const t = top.filter((i) => i.phase === ph).length;
    const f = fu.filter((i) => i.phase === ph).length;
    const d = items.filter((i) => i.phase === ph && i.state === 'done').length;
    return [ph ?? 'unphased', t, f, d, t + f - d];
  })), '');
  const wsList = [...new Set(items.map((i) => i.workstream ?? '—'))].sort();
  p('Primary workstream (first in the WS cell; rows naming several count once here):', '');
  p(table(['Workstream', 'Top-level', 'Follow-up', 'Done', 'Open'], wsList.map((w) => {
    const of = items.filter((i) => (i.workstream ?? '—') === w);
    return [w, of.filter((i) => i.top_level).length, of.filter((i) => !i.top_level).length, of.filter((i) => i.state === 'done').length, of.filter((i) => i.state !== 'done').length];
  })), '');

  p('## 4. States', '');
  p('Normalised state (todo · brief · doing · review · done · blocked) by row type. `done` includes rows closed as obsolete (resolution `closed`).', '');
  p(table(['State', 'Top-level', 'Follow-up', 'All'], STATES.map((st) => [st, top.filter((i) => i.state === st).length, fu.filter((i) => i.state === st).length, items.filter((i) => i.state === st).length])), '');
  const closed = items.filter((i) => i.resolution === 'closed').length;
  const unrec = items.filter((i) => !i.state_recognised && !i.summary_row);
  p(`Of the done rows, ${closed} are closed as obsolete or superseded rather than built. ${items.filter((i) => i.summary_row).length} P3/P4 summary rows have no status column and import as \`todo\`. ${unrec.length} rows begin with a word the normaliser does not know (imported as \`todo\`, listed in §8).`, '');
  const b = r.board;
  p('### The status board\'s two bars, re-derived', '');
  p('Rules of `scripts/status-site/scoreboard.mjs` re-implemented on the imported items: bar 1 counts Phase 1 top-level rows (`P1-<ws>-<n>`) by the board\'s classes; bar 2 counts Phase 1 top-level rows plus every follow-up row as done, schedulable or owner-blocked (Phase 1 blockers from `docs/status/scoreboard.json`, follow-up blockers from the verdict and the board\'s owner vocabulary).', '');
  p(table(['Bar', 'Total', 'Done', 'Partial', 'Review', 'To do'], [[b.bar1.label, b.bar1.total, b.bar1.done, b.bar1.partial, b.bar1.review, b.bar1.todo]]), '');
  p(table(['Bar', 'Total', 'Done', 'Schedulable', 'Owner-blocked'], [[b.bar2.label, b.bar2.total, b.bar2.done, b.bar2.schedulable, b.bar2.owner_blocked]]), '');
  p(`Follow-up rows by the board's classes: ${b.follow.done} done · ${b.follow.partial} partial or review · ${b.follow.todo} to do (${b.bar2.follow_blocked} owner-blocked, ${b.bar2.follow_open} schedulable).`, '');

  p('## 5. Relations: origins, dependencies, cycles, duplicates', '');
  const o = r.stats.origins;
  p('Follow-up origin (`spawned_by`) by the rule that found it (rules in `lib/relations.mjs` and `docs/10` §2):', '');
  p(table(['Rule', 'Rows'], Object.entries(o.byRule).map(([k, v]) => [k === 'none' ? 'none (orphan)' : k, v])), '');
  p(`Rows where the Origin column and the id prefix point at different existing items: ${o.prefixDisagree.length} (the Origin column wins; examples: ${o.prefixDisagree.slice(0, 5).map((x) => `\`${x.id}\` → ${x.origin} (prefix: ${x.by_prefix})`).join(', ') || 'none'}).`, '');
  const orphanKinds = count(o.orphans, (x) => x.origin_text_kind ?? 'no origin text');
  p(`**Orphan follow-ups (no origin item found): ${o.orphans.length}.** By what their Origin text names: ${Object.entries(orphanKinds).map(([k, v]) => `${k} ${v}`).join(' · ') || '—'}.`, '');
  p(list(o.orphans, (x) => `- \`${x.id}\` — origin: ${short(x.origin_text ?? '—', 90)}`, 40), '');
  const ud = r.stats.unresolvedDeps;
  p(`**Unresolved dependency ids: ${ud.length}** (id-shaped tokens in the Depends column that match no row, decision or ADR).`, '');
  p(list(ud, (x) => `- \`${x.id}\` depends on \`${x.depends}\``, 40), '');
  const withText = items.filter((i) => i.depends_text);
  p(`Depends cells with text the parser kept as \`depends_text\` (not ids): ${withText.length}; examples: ${withText.slice(0, 6).map((i) => `\`${i.id}\`: "${short(i.depends_text, 50)}"`).join(' · ') || 'none'}.`, '');
  const c = r.stats.cycles;
  p(`**Cycles in depends_on:** declared Depends column ${c.declared.length}; including the waits named in status verdicts ${c.with_status.length}; in spawned_by ${c.spawned_by.length}.`, '');
  p(list([...c.declared.map((x) => ['declared', x]), ...c.with_status.map((x) => ['with status', x]), ...c.spawned_by.map((x) => ['spawned_by', x])], ([k, x]) => `- ${k}: ${x.map((y) => `\`${y}\``).join(' → ')} → \`${x[0]}\``, 30), '');
  p(`**Duplicate ids: ${r.stats.duplicates.length}**${r.stats.duplicates.length ? ` — ${r.stats.duplicates.map((d) => `\`${d.id}\` (line ${d.line}, imported as \`${d.id}~2\`)`).join(', ')}` : ''}.`, '');
  const malformed = items.filter((i) => i.malformed);
  p(`**Rows with an unexpected cell count: ${malformed.length}** (kept by position; extra cells folded into \`follow_ups_text\`).`, '');
  p(list(malformed, (i) => `- \`${i.id}\` (line ${i.source.line}): ${i.malformed}`, 20), '');

  p('## 6. Evaluation of the work', '');
  p('Evidence strength of every `done` row: **3** a walkthrough or test report that exists on disk (cited in the row, or naming the row in its title or header); **2** a commit, PR or test counts (or an existing code/doc file cited); **1** only a wave, date or decision mention; **0** nothing.', '');
  const grades = [0, 1, 2, 3];
  const doneTop = done.filter((e) => e.top_level);
  const doneFu = done.filter((e) => !e.top_level);
  p(table(['Grade', 'Top-level done', 'Follow-up done', 'All done', 'Share'], grades.map((g) => {
    const a = done.filter((e) => e.grade === g).length;
    return [g, doneTop.filter((e) => e.grade === g).length, doneFu.filter((e) => e.grade === g).length, a, pct(a, done.length)];
  })), '');
  const lifted = done.filter((e) => e.lifted_by_artefact).length;
  p(`${lifted} rows reach grade 2 only through a cited code or doc file that exists (no commit, PR or test count). By phase:`, '');
  p(table(['Phase', 'Done', 'Grade 0', '1', '2', '3'], ['CT', 'P0', 'P1', 'P2', null].map((ph) => {
    const d = done.filter((e) => e.phase === ph);
    return [ph ?? 'unphased', d.length, ...grades.map((g) => d.filter((e) => e.grade === g).length)];
  })), '');
  const noLink = done.filter((e) => !e.has_evidence_link);
  p(`**Done rows with no evidence link** (no URL, commit, PR or path in the row itself): ${noLink.length} of ${done.length}.`, '');
  const toVerify = ev.filter((e) => e.to_verify);
  const low = done.filter((e) => e.grade <= 1 && r.checklistItems.find((i) => i.id === e.id)?.resolution !== 'closed');
  p(`### To verify: ${toVerify.length} rows`, '');
  p(`Done rows at grade 0–1 (closed-as-obsolete rows excluded): **${low.length}**. They import with \`to_verify\` set and go to the coordinator's queue (docs/10 §3).`, '');
  p(list(low, (e) => { const it = r.checklistItems.find((i) => i.id === e.id); return `- \`${e.id}\` (grade ${e.grade}) — ${short(it?.title, 70)} — status: ${short(it?.state_verdict, 70)}`; }, 80), '');
  const walk = done.filter((e) => e.walkthrough);
  const wc = count(walk, (e) => e.walkthrough.status);
  p(`### Walkthrough required and done: ${walk.length} rows`, '');
  p(table(['Walkthrough found', 'Rows'], [
    ['cited in the row and on disk', wc.cited ?? 0],
    ['a report names the row', wc.indexed ?? 0],
    ['only a report of the same wave and workstream (weak)', wc['wave-report'] ?? 0],
    ['cited but the file is missing', wc['cited-missing'] ?? 0],
    ['none', wc.none ?? 0],
  ]), '');
  const noWalk = walk.filter((e) => ['none', 'cited-missing'].includes(e.walkthrough.status));
  p(list(noWalk, (e) => `- \`${e.id}\` — ${e.walkthrough.status}${e.walkthrough.paths.length ? `: ${e.walkthrough.paths.join(', ')}` : ''}`, 60), '');
  const missing = done.filter((e) => e.missing_paths?.length);
  p(`Done rows citing a path that does not exist in the repository: ${missing.length} (paths moved or renamed since; listed per row in \`evaluation.json\` \`missing_paths\`).`, '');
  const blocked = ev.filter((e) => e.blocker);
  const bc = count(blocked, (e) => e.blocker.category);
  p(`### Blocked and waiting rows: ${blocked.length}`, '');
  p(`Rows not done whose verdict names a blocker (state \`blocked\`: ${items.filter((i) => i.state === 'blocked').length}; others say "after X" or "waits on X").`, '');
  p(table(['Blocker', 'Rows'], Object.entries(bc).sort((a, b2) => b2[1] - a[1]).map(([k, v]) => [k, v])), '');
  const byTarget = count(blocked.filter((e) => e.blocker.target), (e) => e.blocker.target);
  const stale = blocked.filter((e) => /^stale/.test(e.blocker.subtype ?? ''));
  p(`**Stale blockers: ${stale.length}** — the verdict names a blocker that is already resolved (a closed card in docs/09 or a done row): ${stale.map((e) => `\`${e.id}\` → ${e.blocker.target}`).join(', ') || 'none'}. These import as \`to_verify\` too.`, '');
  p(`Most-cited blockers: ${Object.entries(byTarget).sort((a, b2) => b2[1] - a[1]).slice(0, 12).map(([k, v]) => `\`${k}\` ${v}`).join(' · ')}.`, '');
  p(list(blocked.filter((e) => e.blocker.category !== 'another task'), (e) => `- \`${e.id}\` — ${e.blocker.category}${e.blocker.subtype ? ` (${e.blocker.subtype})` : ''}: ${short(e.blocker.phrase, 80)}`, 50), '');

  p('## 7. Decisions', '');
  const ds = r.decisions;
  p(table(['Decision kind', 'Type', 'Open', 'Closed'], Object.entries(count(ds, (d) => `${d.decision_kind}|${d.decision_type}`)).map(([k]) => {
    const [dk, dt] = k.split('|');
    const of = ds.filter((d) => d.decision_kind === dk && d.decision_type === dt);
    return [dk, dt, of.filter((d) => d.state === 'open').length, of.filter((d) => d.state === 'closed').length];
  })), '');
  p('Open decisions (the owner\'s inbox at import):', '');
  p(list(ds.filter((d) => d.decision_kind === 'open decision' && d.state === 'open'), (d) => `- \`${d.id}\` (${d.open_kind}) — ${short(d.title, 120)}`, 40), '');
  const openLead = ds.filter((d) => d.decision_type === 'lead decision pending' && d.decision_kind === 'log entry' && d.state === 'open');
  p(`Lead decisions still pending the owner's confirmation (after L425's rule): ${openLead.length}${openLead.length ? ` — ${openLead.map((d) => d.id).join(', ')}` : ''}.`, '');

  p('## 8. What the parser could not handle', '');
  p(`- **Unrecognised status words** (${unrec.length}): ${unrec.slice(0, 12).map((i) => `\`${i.id}\` "${short(i.state_verdict, 40)}"`).join(' · ') || 'none'}.`);
  const contra = ev.filter((e) => e.contradiction && e.contradiction !== 'unrecognised status word');
  const ck = count(contra, (e) => e.contradiction.replace(/".*"/, '"…"'));
  p(`- **Status text that contradicts the normalised state** (${contra.length}; heuristic word match on the verdict, history excluded): ${Object.entries(ck).map(([k, v]) => `${k} ${v}`).join(' · ')}. Examples: ${contra.slice(0, 8).map((e) => `\`${e.id}\` (${e.contradiction})`).join(' · ')}.`);
  p('- **Free-text origins**: Origin cells such as "wave 1 setup", "A report", "review of the Sonnet waves" name a wave or a review, not a row; those rows are orphans unless another row lists them or their id prefix resolves.');
  p('- **Merged cells and folded columns**: rows whose status was written twice or carry an Evidence column (see §5) keep the first columns by position; the parser cannot tell an Evidence cell from a Follow-ups cell.');
  p('- **Wave names**: waves are recognised as "wave 36 H", "E2 wave 5", "wave BETA-AI-1" and "C 32 merged"; other spellings ("H 36\'s census", "the wave that fixed …") are not.');
  p('- **Commit hashes** are taken only from code spans, parentheses or after merge/commit/main words, so a bare hex word in prose is missed on purpose.');
  p('- **Kind detection** (`chore`) is a wording heuristic; rows such as "Lead/owner: confirm …" become chores, a human step written inside a technical row does not.');
  p('- **Pending lead decisions** dated on or before 2026-10-24 are closed by L425\'s rule (confirm rows closed as the lead\'s) unless an open card cites them; this is an inference, not a per-entry record.');
  p('');
  return `${out.join('\n')}\n`;
}
